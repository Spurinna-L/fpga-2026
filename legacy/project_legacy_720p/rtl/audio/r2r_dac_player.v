//=============================================================================
// r2r_dac_player.v  —  从 BRAM 定速读出 PCM → 数字音量 → 8bit R-2R DAC
//-----------------------------------------------------------------------------
//  【一句话】
//    按 48kHz 的节拍，一个接一个地把 audio_bram 里的 16bit 采样取出来，
//    调好音量、压成 8bit 无符号码，送到板载 R-2R 电阻网络变成模拟声音。
//
//        ┌────────────┐  16bit PCM   ┌──────────────┐  ┌──────────┐ 8bit  ┌──────────┐
//        │ audio_bram │─────────────▶│ 本模块        │─▶│ 数字音量  │─────▶│ R-2R DAC │──▶ 喇叭
//        │ (环形缓冲)  │   rd_addr    │ 采样节拍产生  │  │ +格式转换 │ 码    │ (8 个 IO) │──▶ 喇叭
//        └────────────┘◀──fill(可读)─└──────────────┘  └──────────┘       └──────────┘
//
// ============================================================================
// 一、R-2R DAC 是什么（先看这段，不然代码看不懂）
// ============================================================================
//  EG4S20 板上有 8 个 IO：B14,B15,B16,C15,C16,E13,E16,F16。它们同时连到
//  8 个 LED 和一片 R-2R 电阻网络。把这 8 个 IO 当成一个 8bit 数字口：
//     输出 0   → 约 0V
//     输出 128 → 约 Vref/2
//     输出 255 → 约 Vref
//  也就是 256 个电压台阶。我们按采样率不停更新这个数，输出端就是模拟波形。
//
//  声音是有正有负的交流信号，而 R-2R 只能输出 0..255。所以约定：
//     码 128 = 零点/静音；>128 正半周；<128 负半周。
//  板上音频通路有隔直电容，会把 Vref/2 这个直流偏置滤掉，于是喇叭听到纯交流。
//
// ============================================================================
// 二、48kHz 采样节拍怎么来（余数累加器）
// ============================================================================
//  本模块时钟 clk = 50MHz。50MHz / 48kHz = 1041.666...不是整数，
//  不能用"数到 1042 产生一次"（那样会有 0.03% 频率误差），
//  所以用余数累加器做精确分频：
//       每拍   acc = acc + SAMPLE_HZ
//       当 acc >= CLK_HZ： acc = acc - CLK_HZ + SAMPLE_HZ，同时输出一次节拍
//  长期平均频率恰好 = SAMPLE_HZ，只有 ±1 个时钟(20ns)的抖动，人耳听不出。
//
// ============================================================================
// 三、流式播放怎么实现（环形缓冲）
// ============================================================================
//  BRAM 被当作"环形缓冲"：写指针由 wav_to_pcm 推进、读指针由本模块推进，
//  两者各自回卷，谁也不等谁——这就是"边读边播"。
//  顶层把"可读采样数" fill = 写入总数 - 已读出数 送进来：
//    * fill != 0  → 有数据可读：按 48kHz 节拍取一个采样，地址 +1（到顶回 0）；
//    * fill == 0  → 断音(underrun)：本拍不取，dac_out 保持上一值，等数据补上；
//    * 启动：fill 攒够领先量(或文件已读完)才开始；停机：文件读完且排空后停下。
//  【关键·时序技巧】
//    BRAM 是同步读（地址打进去、下一拍才出数据）。因为播放节拍只有 48kHz，
//    地址在两次节拍之间保持约 1000 拍不动，所以 rd_data 早就稳定成了"当前
//    地址对应的采样"。于是我们在节拍到来时直接采 rd_data 即可，无需额外等待。
//
// ============================================================================
// 四、三级流水线
//   第1级 capture：节拍到 → pcm_lat = rd_data，并把地址 +1
//   第2级 volume ：pcm_vol = pcm_lat * volume / 256（有符号乘法）
//   第3级 convert：dac_out = pcm_vol[15:8] ^ 8'h80（有符号→无符号，128 为中点）
//   拆三级是为了 50MHz 下时序宽松（乘法、加法各占一拍）。
//=============================================================================
`timescale 1ns / 1ps

module r2r_dac_player #(
    parameter integer CLK_HZ    = 50_000_000,   // 工作时钟频率
    parameter integer SAMPLE_HZ = 48_000,       // 音频采样率
    parameter integer AW        = 15,
    parameter integer DEPTH     = (1 << AW)
)(
    input  wire          clk,               // 工作时钟（接 50MHz）
    input  wire          rst_n,             // 低有效复位

    // ---------- 与 audio_bram 读口对接 ----------
    output wire [AW-1:0] bram_addr,         // 读地址（组合输出，接到 BRAM）
    input  wire [15:0]   bram_data,         // BRAM 读出的采样（晚 1 拍）

    // ---------- 流式控制 / 信息 ----------
    input  wire [31:0]   fill,              // 环形缓冲里"可读"的采样数（=写入总数-已读出数）
    input  wire          start,             // 1 = 请求启动播放（攒够领先量 或 文件已读完）
    input  wire          eof,               // 1 = 文件已全部进入缓冲（播完即可停机）
    input  wire [7:0]    volume,            // 数字音量 0..255（128≈一半）

    // ---------- 输出 ----------
    output reg  [7:0]    dac_out,           // 8bit R-2R DAC 码（128 = 中点/静音）
    output reg  [31:0]   rd_count           // 已读出采样总数（回给顶层算 fill）
);

    //-------------------------------------------------------------------------
    // 1) 读地址寄存器（直接驱动 BRAM 地址，环形回卷）
    //    地址在两次节拍之间保持约 1000 拍不动，BRAM 的同步读数据早就稳定，
    //    所以节拍到来时直接采 bram_data 即可（见下面第 4 级）。
    //-------------------------------------------------------------------------
    reg [AW-1:0] rd_addr;
    assign bram_addr = rd_addr;

    //-------------------------------------------------------------------------
    // 2) 48kHz 采样节拍（余数累加器，50MHz 下精确分频）
    //-------------------------------------------------------------------------
    reg [31:0] tick_acc;
    // 累加器"存够了"一个整数时钟周期 → 本拍输出一次采样节拍。
    wire       sample_tick = (tick_acc >= CLK_HZ);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            tick_acc <= 32'd0;
        else if (sample_tick)
            tick_acc <= tick_acc - CLK_HZ + SAMPLE_HZ;   // 扣掉整数、留下余数
        else
            tick_acc <= tick_acc + SAMPLE_HZ;            // 每拍累加
    end

    //-------------------------------------------------------------------------
    // 3) 播放状态机（流式）
    //    started：一旦启动就保持播放；仅当"文件已读完 且 缓冲排空"才停机。
    //    断音(underrun)：fill==0 时这一拍不取新采样，dac_out 保持上一个值，
    //                   等上游把数据补上再继续（避免读出垃圾/爆音）。
    //-------------------------------------------------------------------------
    reg started;

    //-------------------------------------------------------------------------
    // 4) 第 1 级 capture：节拍到来且有数据 → 抓当前采样，并让地址前进
    //-------------------------------------------------------------------------
    reg [15:0] pcm_lat;     // 抓到的原始 16bit 采样（有符号）
    reg        v_cap;       // "本拍 pcm_lat 有效"的 1 拍脉冲

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rd_addr  <= {AW{1'b0}};
            rd_count <= 32'd0;
            started  <= 1'b0;
            pcm_lat  <= 16'd0;
            v_cap    <= 1'b0;
        end else begin
            v_cap <= 1'b0;

            // --- 启动 / 停机 ---
            if (!started) begin
                if (start) started <= 1'b1;            // 攒够领先量 → 开播
            end else if (eof && (fill == 32'd0)) begin
                started <= 1'b0;                       // 播完最后一滴 → 停机
            end

            // --- 取采样（环形） ---
            if (started && sample_tick && (fill != 32'd0)) begin
                pcm_lat  <= bram_data;                 // 当前地址对应的采样
                v_cap    <= 1'b1;
                rd_addr  <= (rd_addr == {AW{1'b1}}) ? {AW{1'b0}} : (rd_addr + 1'b1);
                rd_count <= rd_count + 32'd1;          // 累计已读数，供顶层算 fill
            end
            // 否则（fill==0，断音）：不动地址、不涨 rd_count，dac_out 保持
        end
    end

    //-------------------------------------------------------------------------
    // 5) 第 2 级 volume：pcm_vol = pcm_lat * volume / 256
    //    volume 0..255；先算 32bit 乘积，再取 [23:8] 相当于 >>8 后取低 16bit。
    //-------------------------------------------------------------------------
    wire signed [31:0] pcm_scaled   = $signed(pcm_lat) * $signed({1'b0, volume});
    wire signed [15:0] pcm_vol_next = pcm_scaled[23:8];

    reg signed [15:0] pcm_vol;
    reg               v_vol;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pcm_vol <= 16'sd0;
            v_vol   <= 1'b0;
        end else begin
            v_vol <= v_cap;
            if (v_cap)
                pcm_vol <= pcm_vol_next;
        end
    end

    //-------------------------------------------------------------------------
    // 6) 第 3 级 convert：有符号 16bit → 无符号 8bit DAC 码
    //    取高 8 位压缩量程，再异或 0x80 把 0 平移到中点：
    //      +32767 → 0x7F ^ 0x80 = 0xFF = 255（最大正电压）
    //       0     → 0x00 ^ 0x80 = 0x80 = 128（中点/静音）
    //      -32768 → 0x80 ^ 0x80 = 0x00 = 0  （最小/负电压）
    //-------------------------------------------------------------------------
    wire [7:0] dac_code = pcm_vol[15:8] ^ 8'h80;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            dac_out <= 8'h80;               // 上电先给中点 = 静音
        else if (v_vol)
            dac_out <= dac_code;            // 有新采样才更新
        else if (!started)
            dac_out <= 8'h80;               // 未播放/已播完：回到中点静音
    end

endmodule
