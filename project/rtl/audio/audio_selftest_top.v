//=============================================================================
// audio_selftest_top.v  —  R-2R 音频通路「上板自测」顶层
//-----------------------------------------------------------------------------
//  【为什么要写这个文件】
//     正式链路是：
//         SD 卡 → sd_ctrl → fat32_reader → wav_to_pcm → BRAM → R-2R DAC
//     但 fat32_reader 目前还是空壳（只有 TODO），SD 卡那边吐不出字节流。
//     所以这里「人工造」一段合法的 WAV 字节流，在芯片内部直接喂给 wav_r2r_top，
//     用来验证下面这 3 个模块在**真实硬件**上能不能跑通：
//           wav_to_pcm     —— 解析 WAV 头 + 把 PCM 写进 BRAM
//           audio_bram     —— 存采样
//           r2r_dac_player —— 48kHz 读出 + 音量 + 驱动 R-2R DAC
//
//  【自造的 WAV 长什么样】
//     48kHz / 16bit / 单声道；8192 个采样；内容是 750Hz 方波。
//     → 下载到板子后，喇叭里听到一个约 0.17s 的 750Hz 单音「嘟」。
//        （流式播放：缓冲一攒够就出声，播完整段后停止。）
//
//  【怎么「喂」字节】—— 就是实现 wav_to_pcm 的 valid/ready 握手
//     s_valid / s_data：本拍给出的那个字节
//     s_ready        ：wav_to_pcm 回答「我收下了」
//     规则：某一拍 s_valid=1 且 s_ready=1  →  这个字节被消费，下一拍换下一个。
//     本文件用一个计数器 bidx（第几个字节）来实现：
//         bidx = 0,1,2,...,NBYTES-1  依次送出去，全部送完后 s_valid 自动拉低。
//
//  【流式播放·本版已改】wav_r2r_top 现在是"边收边解码边播"：
//     下载后不必等整个文件灌完——缓冲攒够一小段领先量就开始出声，
//     播放与"上游送字节"并行进行。本自测顶层只是把假 WAV 一次喂完，
//     8192 个采样 @48kHz 约 0.17s，播完即停（不再是无限循环）。
//
//  【注意】本文件只在「音频自测工程（audio_test1）」里用，不参与正式工程
//          main_project 的综合。
//=============================================================================
`timescale 1ns / 1ps

module audio_selftest_top (
    input  wire       clk_50m,     // R7   板载 50MHz 有源晶振
    input  wire       rst_n_in,    // A9   SW0，低有效复位
    output wire [7:0] dac_out,     // B14,B15,B16,C15,C16,E13,E16,F16 → 外接 R-2R 网络
    output wire       audio_pwm    // F3   → 板载低通 + FM8002A 功放 → 3.5mm/喇叭
);

    //=========================================================================
    // 0) 参数
    //=========================================================================
    localparam integer AW     = 13;                 // BRAM 地址位宽：2^13 = 8192 个采样
    localparam integer NSAMP  = 8192;               // 自造 WAV 里放多少个采样
    localparam integer HDRLEN = 44;                 // 标准 WAV 头固定 44 字节
    localparam integer NBYTES = HDRLEN + NSAMP * 2; // 总字节数 = 44 + 16384 = 16428

    wire rst_n = rst_n_in;      // 本工程只有一个时钟域，复位可以直接用

    wire [7:0] dac_code;        // wav_r2r_top 输出的 8bit DAC 码（128 = 静音中点）

    //=========================================================================
    // 1) 字节流计数器：现在该送第几个字节？
    //=========================================================================
    reg  [14:0] bidx;           // 0 .. NBYTES-1（16428 < 32768，15bit 够用）

    wire        s_valid;        // 送给 wav_to_pcm：本拍有一个字节
    wire [7:0]  s_data;         // 送给 wav_to_pcm：这个字节
    wire        s_ready;        // 来自 wav_to_pcm：它收下了

    assign s_valid = (bidx < NBYTES[14:0]);   // 全部送完就自动拉低

    always @(posedge clk_50m) begin
        if (!rst_n)
            bidx <= 15'd0;
        else if (s_valid && s_ready)          // 握手成功 → 换下一个字节
            bidx <= bidx + 15'd1;
    end

    //=========================================================================
    // 2) 当前这个字节从哪来？
    //      bidx < 44   → 取下面的 WAV 头常量
    //      bidx >= 44  → 取实时算出来的 PCM 数据
    //=========================================================================
    wire [14:0] n     = bidx - 15'd44;   // data 区内的字节序号
    wire [12:0] samp  = n[13:1];         // 第几个采样（n/2，因为 16bit = 2 字节）
    wire        b_hi  = n[0];            // 0 = 先发低字节，1 = 后发高字节（小端）

    // 750Hz 方波：samp[5] 每 32 个采样翻转一次 → 周期 64 个采样
    //            48000 / 64 = 750Hz  （人耳听得很清楚）
    wire [15:0] pcm   = samp[5] ? 16'h9000 : 16'h7000;   // 有符号 -28672 / +28672
    wire [7:0]  pcm_b = b_hi ? pcm[15:8] : pcm[7:0];     // 小端：低字节先

    // 44 字节标准 WAV 头。
    // 数值已经按「字节到达顺序」排好（小端字段已经手工翻好顺序），直接照抄即可。
    //   data 大小 = 16384 字节 (0x4000)      → 小端 00 40 00 00
    //   RIFF 大小 = 36 + 16384 = 16420       → 小端 24 40 00 00
    //   采样率 48000 (0xBB80)                → 小端 80 BB 00 00
    //   字节率 96000 (0x17700)               → 小端 00 77 01 00
    reg [7:0] cur_byte;
    always @(*) begin
        case (bidx)
            // ---------- "RIFF" ----------
            15'd0 : cur_byte = 8'h52;   // 'R'
            15'd1 : cur_byte = 8'h49;   // 'I'
            15'd2 : cur_byte = 8'h46;   // 'F'
            15'd3 : cur_byte = 8'h46;   // 'F'
            // ---------- RIFF 块大小 = 16420 (小端) ----------
            15'd4 : cur_byte = 8'h24;
            15'd5 : cur_byte = 8'h40;
            15'd6 : cur_byte = 8'h00;
            15'd7 : cur_byte = 8'h00;
            // ---------- "WAVE" ----------
            15'd8 : cur_byte = 8'h57;   // 'W'
            15'd9 : cur_byte = 8'h41;   // 'A'
            15'd10: cur_byte = 8'h56;   // 'V'
            15'd11: cur_byte = 8'h45;   // 'E'
            // ---------- "fmt " ----------
            15'd12: cur_byte = 8'h66;   // 'f'
            15'd13: cur_byte = 8'h6D;   // 'm'
            15'd14: cur_byte = 8'h74;   // 't'
            15'd15: cur_byte = 8'h20;   // ' '
            // ---------- fmt 子块大小 = 16 (小端) ----------
            15'd16: cur_byte = 8'h10;
            15'd17: cur_byte = 8'h00;
            15'd18: cur_byte = 8'h00;
            15'd19: cur_byte = 8'h00;
            // ---------- 编码格式 = 1 (PCM，小端) ----------
            15'd20: cur_byte = 8'h01;
            15'd21: cur_byte = 8'h00;
            // ---------- 声道数 = 1 (小端) ----------
            15'd22: cur_byte = 8'h01;
            15'd23: cur_byte = 8'h00;
            // ---------- 采样率 = 48000 (小端) ----------
            15'd24: cur_byte = 8'h80;
            15'd25: cur_byte = 8'hBB;
            15'd26: cur_byte = 8'h00;
            15'd27: cur_byte = 8'h00;
            // ---------- 字节率 = 96000 (小端) ----------
            15'd28: cur_byte = 8'h00;
            15'd29: cur_byte = 8'h77;
            15'd30: cur_byte = 8'h01;
            15'd31: cur_byte = 8'h00;
            // ---------- 块对齐 = 2 (小端) ----------
            15'd32: cur_byte = 8'h02;
            15'd33: cur_byte = 8'h00;
            // ---------- 位宽 = 16 (小端) ----------
            15'd34: cur_byte = 8'h10;
            15'd35: cur_byte = 8'h00;
            // ---------- "data" ----------
            15'd36: cur_byte = 8'h64;   // 'd'
            15'd37: cur_byte = 8'h61;   // 'a'
            15'd38: cur_byte = 8'h74;   // 't'
            15'd39: cur_byte = 8'h61;   // 'a'
            // ---------- data 块大小 = 16384 (小端) ----------
            15'd40: cur_byte = 8'h00;
            15'd41: cur_byte = 8'h40;
            15'd42: cur_byte = 8'h00;
            15'd43: cur_byte = 8'h00;
            // ---------- 44 之后全是 PCM 数据 ----------
            default: cur_byte = pcm_b;
        endcase
    end
    assign s_data = cur_byte;

    //=========================================================================
    // 3) 把造好的字节流灌进被测链路
    //=========================================================================
    wav_r2r_top #(
        .AW        (AW),
        .CLK_HZ    (50_000_000),
        .SAMPLE_HZ (48_000)
    ) u_dut (
        .clk          (clk_50m),
        .rst_n        (rst_n),
        .s_valid      (s_valid),      // → 本拍有字节
        .s_data       (s_data),       // → 这个字节
        .s_ready      (s_ready),      // ← 它收下了
        .volume       (8'd255),       // 固定音量：最大（0=静音，255=最响）
        .dac_out      (dac_code),     // → 8bit DAC 码（下面两条通路都用它）
        .header_ok    (),             // 调试用，本工程不引出引脚（可用 ChipWatcher 观察）
        .load_done    (),
        .sample_count (),
        .sample_rate  (),
        .channels     (),
        .bits         ()
    );

    //=========================================================================
    // 4) 把同一个 8bit DAC 码送到两条硬件通路（用哪条都能听）
    //=========================================================================
    // 通路①（你自己外接 R-2R 电阻网络时用）：
    //     8bit 并行码直接出到 B14..F16。板子上这 8 个脚本来是 8 个 LED，
    //     官方底板并没有在这组脚上引出音频插座，所以要用这条通路必须自己
    //     搭 8 个电阻的 R-2R 网络，再把输出接耳机/喇叭。
    assign dac_out = dac_code;

    // 通路②（推存，直接用板载现成音频口）：
    //     1 阶 Σ-Δ（sigma-delta）调制，把 8bit 码变成 1bit 位流，输出到 F3。
    //     F3 在官方底板上去往「低通 + FM8002A 功放 + 3.5mm 耳机座」，
    //     所以插上耳机、直接下载就能听到声音。
    //
    //     原理：把 8bit 码当“增量”每拍累加到 8bit 累加器里，取进位位当输出。
    //     长期平均占空比 = dac_code/256，经外部低通滤波后即还原成模拟电压：
    //         dac_code = 128（静音）→ 占空比 50%  → 平均 1.65V → 被隔直电容滤掉 → 无声
    //         dac_code = 239        → 占空比 93%  → 高电平
    //         dac_code = 16         → 占空比 6%   → 低电平
    reg [8:0] sd_acc;                 // 9 位：低 8 位是累加器，最高位是进位
    always @(posedge clk_50m) begin
        if (!rst_n) sd_acc <= 9'd0;
        else        sd_acc <= {1'b0, sd_acc[7:0]} + {1'b0, dac_code};
    end
    assign audio_pwm = sd_acc[8];

    // 说明：u_dut 的 header_ok/load_done/sample_count 等输出留空，是因为本工程
    //       只有 11 个引脚，没有多余的 LED 可用（板载 8 个 LED 与 dac_out 复用）。
    //       想观察它们，用 TD 的 ChipWatcher 功能即可（见使用说明）。

endmodule
