//=============================================================================
// logo_overlay.v — 左上角 Logo 水印图层（M2 扩展④ 第二层叠加）
//-----------------------------------------------------------------------------
// 功能：
//   在画面左上角叠加一个 32×32 的图形 Logo（安路标识）。
//   与 osd_composer.v（右上角参数面板）互不重叠、互不依赖，可同时开启。
//
// 叠加方式（逐像素二选一，零乘法、零 BRAM、零延迟）：
//   Logo 点阵自带 1bit「不透明位」：
//     opaque = 1 → 输出 Logo 像素（RGB555 还原成 24bit）
//     opaque = 0 → 原像素**逐位直通**（透明区完全不影响原图）
//   因此背景图（含 A/B 转场中间帧）在 Logo 透明处 100% 保持原样。
//
// 时钟/复位：纯组合逻辑（同拍直通）；无复位、无 BRAM、无 IP 依赖。
//
// 接口：
//   in  I_de / I_x / I_y / I_rgb   来自上层的像素（必须与 I_rgb 同拍）
//   in  I_en                       Logo 图层总开关（0 = 完全直通）
//   out O_de / O_x / O_y / O_rgb   叠加后的像素（坐标/使能原样直通）
//
// 参数/常量：
//   X0 = 8          Logo 左上角 X（左上角留 8px 边距，与右侧 OSD 一致）
//   Y0 = 8          Logo 左上角 Y
//   SIZE = 32       Logo 宽高
//   ROM 为 32×32，内容上下居中留透明边（等比缩放不变形，见生成器）
//
// 内部例化：
//   logo_data_32x32   32×32 点阵，组合 LUT ROM（0 BRAM，0 拍延迟）
//
// 备注：
//   1) 本模块**不引入任何流水延迟**：O_de/O_x/O_y 与 I_* 同拍，O_rgb 也是同拍，
//      所以插到 video_post 里既不影响 hs/vs 的既有延迟对齐，也不会改变
//      帧缓存/行缓冲/转场的行为 —— 只改「最终送出去的像素值」。
//      若将来把 ROM 换成同步读 BRAM，必须同时把 I_rgb/I_de/I_x/I_y 打一拍。
//   2) de=0（消隐区）/ 面板外 / I_en=0 全部逐像素直通，绝不污染 HDMI 消隐。
//   3) 想挪位置或换尺寸：改 X0/Y0 与 ROM 即可，叠加逻辑与分辨率无关。
//=============================================================================
`timescale 1ns / 1ps

module logo_overlay(
    input  wire              I_de,
    input  wire [9:0]        I_x,
    input  wire [9:0]        I_y,
    input  wire [23:0]       I_rgb,
    input  wire              I_en,

    output wire              O_de,
    output wire [9:0]        O_x,
    output wire [9:0]        O_y,
    output wire [23:0]       O_rgb
);

    //-------------------------------------------------------------------------
    // 布局常量（左上角，留 8px 边距；改成 10'd0 即贴边）
    //-------------------------------------------------------------------------
    localparam [9:0] X0   = 10'd8;
    localparam [9:0] Y0   = 10'd8;
    localparam [9:0] SIZE = 10'd32;

    //-------------------------------------------------------------------------
    // 坐标 → Logo 内地址
    //-------------------------------------------------------------------------
    wire in_x = (I_x >= X0) && (I_x < (X0 + SIZE));
    wire in_y = (I_y >= Y0) && (I_y < (Y0 + SIZE));

    wire [9:0] dx = I_x - X0;
    wire [9:0] dy = I_y - Y0;

    //-------------------------------------------------------------------------
    // 点阵查表（组合，与像素同拍）
    //-------------------------------------------------------------------------
    wire [15:0] pix;

    logo_data_32x32 u_rom (
        .I_addr ({dy[4:0], dx[4:0]}),   // addr = y*32 + x
        .O_pix  (pix)
    );

    wire        opaque = pix[15];
    // RGB555 → RGB888：高位补低位（v8 = v<<3 | v>>2，误差 ≤ 2）
    wire [23:0] logo_rgb = {
        pix[14:10], pix[14:12],         // R
        pix[ 9: 5], pix[ 9: 7],         // G
        pix[ 4: 0], pix[ 4: 2]          // B
    };

    //-------------------------------------------------------------------------
    // 像素叠加：只有「使能 + 面板内 + de=1 + 该点不透明」才替换
    //-------------------------------------------------------------------------
    wire hit = I_en && I_de && in_x && in_y && opaque;

    assign O_de  = I_de;
    assign O_x   = I_x;
    assign O_y   = I_y;
    assign O_rgb = hit ? logo_rgb : I_rgb;

endmodule
